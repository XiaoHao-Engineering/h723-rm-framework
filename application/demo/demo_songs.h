/**
 * @file demo_songs.h
 * @brief 示例 app 用到的旋律表
 *
 * 设计约定(与框架分层保持一致):
 *   - module 层(modules/alarm/buzzer.c)只提供"播放器" BuzzerPlayMelody();
 *   - app 层(本文件所在层)拥有"歌", 想换曲子/加曲子只改这里, 不动 module。
 *
 * 音符格式: { 频率 Hz, 时长 ms }, 频率填 0 表示休止符。
 *
 * 简谱 -> 频率换算(1=C):
 *   1=262  2=294  3=330  4=349  5=392  6=440  7=494  (Hz, 中央 C 组)
 *   高音(上面一点) ×2, 低音(下面一点) ÷2
 *   升半音(#) ×1.0595, 降半音(b) ÷1.0595
 * 时值: 四分音符 500ms, 八分 250ms, 十六分 125ms, 二分 1000ms
 *
 * @note MC02 的蜂鸣器是无源的, 只能"一次一个音高", 所以这里只能表达旋律,
 *       表达不了和弦/鼓点/滑音。
 */

