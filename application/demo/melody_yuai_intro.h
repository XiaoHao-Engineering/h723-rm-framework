/**
 * @file melody_yuai_intro.h
 * @brief 用户提供的简谱(前奏/主歌段)转成的旋律表
 *
 * 说明:
 *   - 音符完全按用户给的简谱 (5  #4  5  6  7  1  3  2 ...) 录入, 未做增删;
 *   - 简谱里没有标时值, 下面每个音的时长是按"分组 + 唱词节奏"配的,
 *     如果听着快/慢, 直接改数字即可(单位 ms), 或者运行时调 BuzzerSetMelodyTempo();
 *   - 简谱里没有标音区(高低音点), 这里按旋律走向选了八度:
 *       前奏的 5 / #4 走中音(M), "窗外的天气" 一路升到高音(H),
 *       "我也不想看清" 从高音回落。
 *     如果你觉得某一句太高/太低, 把那一句的 M/H 互换即可;
 *   - 蜂鸣器是单音乐器, 只能出主旋律, 和声/拟声("崩吧""wow")只能靠短促音符模拟;
 *   - 曲子有版权, 这里仅按你提供的简谱做格式转换, 供你本机自用。
 *
 * 记号速查(music_notes.h):
 *   M5 = 中音 sol, M4S = 中音 #4, H1 = 高音 do, L5 = 低音 sol
 *   N(音高, 时长ms)
 */

#ifndef MELODY_YUAI_INTRO_H
#define MELODY_YUAI_INTRO_H

#include "buzzer.h"
#include "music_notes.h"

/* ------------------------------------------------------------------
 * 节奏常量(想整体改律动就改这四个值)
 * ------------------------------------------------------------------ */
#define YQ 500U /* 一拍(四分音符) */
#define YE 250U /* 半拍(八分音符) */
#define YS 125U /* 四分之一拍(十六分音符), 用于"哆咯""崩吧"这种快速念白 */
#define YH 1000U /* 两拍, 用于 ~ 延长音 */

static const BuzzerNote_t melody_yuai_intro[] = {
    /* ================= 第一段 ================= */

    /* 1) 5~ | 5 6 5 | 5 6 5   ("嗯~嗒啦嗯 嗒嗯 嗒嗯") */
    N(M5, YH), N(M5, YE), N(M6, YE), N(M5, YQ),
    N(M5, YE), N(M6, YE), N(M5, YQ),

    /* 2) 5 #4 5 #4 5 #4 5   ("哆咯 哆咯 哆咯 哆咯", 快速念白) */
    N(M5, YS), N(M4S, YS), N(M5, YS), N(M4S, YS),
    N(M5, YS), N(M4S, YS), N(M5, YE),

    /* 3) 3 5 3 #4 5   ("em吧 em吧 崩吧 崩吧") */
    N(M3, 375), N(M5, 375), N(M3, YE), N(M4S, YE), N(M5, 750),

    /* ================= 第二段 ================= */

    /* 4) 5 6 5~ | 5 #4 5 | 5 #4 5   ("嗒嘚啦 嘚嗯 嘚欸 吧抱!") */
    N(M5, YE), N(M6, YE), N(M5, YH),
    N(M5, YS), N(M4S, YS), N(M5, YE),
    N(M5, YS), N(M4S, YS), N(M5, YE),

    /* 5) 5 5 #4 5 #4 5 #4 5   ("吧 哆吧 哆 哆 哆 哆 哆 哆") */
    N(M5, YS), N(M5, YS), N(M4S, YS), N(M5, YS),
    N(M4S, YS), N(M5, YS), N(M4S, YS), N(M5, YE),

    /* 6) 5~ | 5 #4 5 #4 5 #4 5   ("哆嗯 哆 哆 哆 哆 哆") */
    N(M5, YH),
    N(M5, YS), N(M4S, YS), N(M5, YS), N(M4S, YS),
    N(M5, YS), N(M4S, YS), N(M5, YE),

    /* 7) 5 #4 5 #4 5 #4 5   ("崩吧" x6, 第一下弹舌) */
    N(M5, YS), N(M4S, YS), N(M5, YS), N(M4S, YS),
    N(M5, YS), N(M4S, YS), N(M5, YE),

    /* 8) 5 6 7 1 3 5 | 5 3 5 3 2   ("wow! 窗外的天气 就像是") */
    N(M5, YE), N(M6, YE), N(M7, YE), N(H1, YE),
    N(H3, YQ), N(H5, YQ),
    N(H5, YE), N(H3, YE), N(H5, YE), N(H3, YE), N(H2, YQ),

    /* 9) 3 5 3 6 7 1 7 6 7   ("你多变的表情") */
    N(M3, YE), N(M5, YE), N(M3, YE), N(M6, YE), N(M7, YE), N(H1, YQ),
    N(H7, YE), N(H6, YE), N(H7, YQ),

    /* 10) 3 5 3 6 7 1 7 6 7   ("下雨了, 雨陪我哭泣") */
    N(M3, YE), N(M5, YE), N(M3, YE), N(M6, YE), N(M7, YE), N(H1, YQ),
    N(H7, YE), N(H6, YE), N(H7, YQ),

    /* 11) 6 7 1   ("看不清") */
    N(M6, YE), N(M7, YE), N(H1, YH),

    /* 12) 7 6 5 3 2   ("我也不想看清~") */
    N(H7, YE), N(H6, YE), N(H5, YE), N(H3, YE), N(H2, YH),
};

#endif /* MELODY_YUAI_INTRO_H */
