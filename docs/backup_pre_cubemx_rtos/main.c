/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* Enable the CPU Cache */

  /* Enable I-Cache---------------------------------------------------------*/
  SCB_EnableICache();

  /* Enable D-Cache---------------------------------------------------------*/
  SCB_EnableDCache();

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* Configure the peripherals common clocks */
  PeriphCommonClock_Config();

  /* USER CODE BEGIN SysInit */
  /* DWT 越早初始化越好: 从这里开始, 后面所有"不能依赖 HAL_GetTick 的延时"
   * (USB 的虚拟拔插、bsp 自检、故障转储里的等待) 才有可靠的计时源。
   * 注意 DWT 是 CPU 周期计数器, 关中断也照常计数, 因此在 __disable_irq()
   * 区域内也是安全的 —— 这正是本工程全部延时的统一时间源。 */
  DWT_Init((uint32_t)(SystemCoreClock / 1000000U));
  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
#if !USE_MINIMAL_TEST
  /* 正常固件: 初始化全部外设(USB/ADC/FDCAN/串口/SPI2...)
   * USE_MINIMAL_TEST=1 时整段跳过, 只保留 bsp 内部自己初始化的
   * 5V 使能 / 定时器(PB15) / SPI6(PA7), 用于把"框架初始化"和"硬件"分开排查 */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_BDMA_Init();
  MX_FDCAN1_Init();
  MX_FDCAN2_Init();
  MX_UART5_Init();
  MX_SPI2_Init();
  MX_TIM3_Init();
  MX_UART7_Init();
  MX_USART1_UART_Init();
  MX_USART2_UART_Init();
  MX_USART3_UART_Init();
  MX_USART10_UART_Init();
  MX_FDCAN3_Init();
  MX_ADC3_Init();
  MX_ADC1_Init();
#if BSP_USB_ENABLE
  /* USB 虚拟串口(视觉/上位机用)。不用 USB 时把 bsp_board.h 里的
   * BSP_USB_ENABLE 改成 0: 少一个 1kHz 级别可能反复进的中断源,
   * 排查"中断风暴/卡顿"时这是第一个值得关掉的外设。 */
  MX_USB_DEVICE_Init();
#endif
#endif /* !USE_MINIMAL_TEST */
  /* USER CODE BEGIN 2 */

#if USE_MINIMAL_TEST
  /* 最小自检固件: 只测 5V / 蜂鸣器 / 彩灯, 不启动 RTOS */
  MinimalTestInit();
#else
  /* 应用层初始化: bsp -> module(app 注册) -> 创建 rtos 任务
   * 注意: 此时还没有启动调度器, 任务不会运行 */
  RobotInit();
  LOGINFO("[main] SystemInit() and RobotInit() done");
#endif /* USE_MINIMAL_TEST */

  /* 注意: 这一句必须在 USER CODE 区内。
   * 本工程的 FreeRTOS 是手工接入的(.ioc 里 FREERTOS 是 Disable),
   * 如果放在生成区, 一旦用 CubeMX 重新生成代码它会被静默删掉,
   * 结果是调度器不启动 -> 任务一个都不跑, 但没有任何报错。 */
#if !USE_MINIMAL_TEST
  osKernelStart();
#endif /* !USE_MINIMAL_TEST */
  /* USER CODE END 2 */

  /* We should never get here as control is now taken by the scheduler */
  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
#if USE_MINIMAL_TEST
    MinimalTestLoop(); /* 最小自检: 灯循环换色 + 蜂鸣器定时响 */
#endif /* USE_MINIMAL_TEST */
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

